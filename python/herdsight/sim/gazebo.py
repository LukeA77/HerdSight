"""Gazebo Harmonic world from a simulated world (Phase 5 plan, step 6; D-11).

`world_sdf` writes an SDF world: ground, the camp's fence, trees, fixed objects that cause false
detections (rocks, troughs), and one model per animal. Animals are simple shapes made for this
project (no third-party meshes): a body box and a head box sized from each animal's measured
length, coloured from a few coat colours. Each animal carries its own semantic label (its index
plus 1) for Gazebo's bounding-box camera, which tells home base in simulation which animals a still
saw and how much of each was visible; rendered images are never scored (D-11). Coordinates: Gazebo's
world frame is east-north-up, the same as the simulator.

Animal poses are then moved during the flight by the herd model (sim/bridge), one implementation
of the movement (Phase 5 plan review, finding 20).
"""

# ruff: noqa: E501  (SDF markup lines)

from __future__ import annotations

from xml.sax.saxutils import escape

import numpy as np

from herdsight.sim.flight import World

MAX_LABELLED_ANIMALS = 254  # labels are kept to 1-254, one per animal
COATS = ((0.08, 0.07, 0.06), (0.45, 0.25, 0.12), (0.85, 0.82, 0.75), (0.30, 0.20, 0.15))


def _box(name: str, size: tuple[float, float, float], pose: str, rgb: tuple[float, ...]) -> str:
    sx, sy, sz = size
    r, g, b = rgb
    return f"""      <link name="{name}">
        <pose>{pose}</pose>
        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material>
        </visual>
      </link>"""


def animal_model(
    i: int, x: float, y: float, yaw: float, length: float, calf: bool, coat: int
) -> str:
    body_l = 0.72 * length
    body_w = 0.32 * length
    body_h = 0.45 * length
    head_l = 0.25 * length
    rgb = COATS[coat % len(COATS)]
    label = i + 1
    return f"""    <model name="animal_{i}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} 0 0 0 {yaw:.4f}</pose>
{_box("body", (body_l, body_w, body_h), f"0 0 {body_h / 2 + 0.3 * length:.3f} 0 0 0", rgb)}
{_box("head", (head_l, 0.6 * body_w, 0.5 * body_h), f"{body_l / 2 + head_l / 2:.3f} 0 {body_h + 0.25 * length:.3f} 0 0 0", rgb)}
      <plugin filename="gz-sim-label-system" name="gz::sim::systems::Label">
        <label>{label}</label>
      </plugin>
    </model>"""


def world_sdf(world: World, name: str = "herdsight_farm", seed: int = 0) -> str:
    if world.herd.n > MAX_LABELLED_ANIMALS:
        raise ValueError(f"at most {MAX_LABELLED_ANIMALS} animals can carry a label")
    rng = np.random.default_rng(seed)
    parts = []
    poly = world.camp.polygon
    for k, (a, b) in enumerate(zip(poly, np.roll(poly, -1, axis=0), strict=True)):
        mid, d = (a + b) / 2, b - a
        parts.append(
            f"""    <model name="fence_{k}"><static>true</static>
      <pose>{mid[0]:.3f} {mid[1]:.3f} 0.6 0 0 {np.arctan2(d[1], d[0]):.4f}</pose>
{_box("rail", (float(np.linalg.norm(d)), 0.08, 1.2), "0 0 0 0 0 0", (0.4, 0.3, 0.2))}
    </model>"""
        )
    for k, (x, y, r) in enumerate(world.trees):
        parts.append(
            f"""    <model name="tree_{k}"><static>true</static><pose>{x:.3f} {y:.3f} 0 0 0 0</pose>
      <link name="canopy"><pose>0 0 {r + 3:.2f} 0 0 0</pose>
        <visual name="v"><geometry><sphere><radius>{r:.2f}</radius></sphere></geometry>
          <material><ambient>0.1 0.3 0.1 1</ambient><diffuse>0.1 0.35 0.1 1</diffuse></material>
        </visual></link>
    </model>"""
        )
    for k, (x, y) in enumerate(world.objects):
        size = tuple(float(v) for v in rng.uniform(0.8, 2.2, 3) * (1, 0.6, 0.5))
        parts.append(
            f"""    <model name="object_{k}"><static>true</static>
      <pose>{x:.3f} {y:.3f} 0 0 0 {rng.uniform(0, np.pi):.3f}</pose>
{_box("o", size, f"0 0 {size[2] / 2:.2f} 0 0 0", (0.5, 0.48, 0.45))}
    </model>"""
        )
    yaws = rng.uniform(-np.pi, np.pi, world.herd.n)
    coats = rng.integers(0, len(COATS), world.herd.n)
    for i, (x, y) in enumerate(world.herd.pos):
        parts.append(
            animal_model(
                i, x, y, yaws[i], float(world.length_m[i]), bool(world.calf[i]), int(coats[i])
            )
        )
    body = "\n".join(parts)
    return f"""<?xml version="1.0"?>
<!-- Generated by python/herdsight/sim/gazebo.py: camp {escape(world.camp.name)}, {world.herd.n} animals.
     Simulation only; rendered animals are never scored (D-11). -->
<sdf version="1.9">
  <world name="{escape(name)}">
    <physics name="1ms" type="ignored"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>
    <plugin filename="gz-sim-air-pressure-system" name="gz::sim::systems::AirPressure"/>
    <plugin filename="gz-sim-magnetometer-system" name="gz::sim::systems::Magnetometer"/>
    <spherical_coordinates><surface_model>EARTH_WGS84</surface_model><world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>52.0</latitude_deg><longitude_deg>-1.5</longitude_deg><elevation>100</elevation></spherical_coordinates>
    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 100 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse><direction>-0.4 0.2 -0.9</direction></light>
    <model name="ground"><static>true</static>
      <link name="l"><collision name="c"><geometry><plane><normal>0 0 1</normal><size>4000 4000</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>4000 4000</size></plane></geometry>
          <material><ambient>0.3 0.45 0.2 1</ambient><diffuse>0.35 0.5 0.22 1</diffuse></material></visual></link>
    </model>
{body}
  </world>
</sdf>
"""
